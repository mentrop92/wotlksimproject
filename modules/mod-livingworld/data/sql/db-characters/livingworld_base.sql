CREATE TABLE IF NOT EXISTS `lw_schedules` (
  `character_guid` INT UNSIGNED NOT NULL,
  `day_mask` TINYINT UNSIGNED NOT NULL DEFAULT 127,
  `preferred_start_minute` SMALLINT UNSIGNED NOT NULL DEFAULT 1080,
  `preferred_end_minute` SMALLINT UNSIGNED NOT NULL DEFAULT 1380,
  `timezone_offset_minutes` SMALLINT NOT NULL DEFAULT 0,
  `next_planned_login` TIMESTAMP NULL DEFAULT NULL,
  `next_planned_logout` TIMESTAMP NULL DEFAULT NULL,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`character_guid`),
  KEY `idx_lw_schedules_next_login` (`next_planned_login`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lw_memories` (
  `memory_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `character_guid` INT UNSIGNED NOT NULL,
  `event_type` VARCHAR(64) NOT NULL,
  `subject_guid` INT UNSIGNED NULL DEFAULT NULL,
  `importance` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `valence` TINYINT NOT NULL DEFAULT 0,
  `payload` TEXT NULL,
  `is_protected` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `occurred_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `expires_at` TIMESTAMP NULL DEFAULT NULL,
  PRIMARY KEY (`memory_id`),
  KEY `idx_lw_memories_owner_time` (`character_guid`, `occurred_at`),
  KEY `idx_lw_memories_subject` (`subject_guid`),
  KEY `idx_lw_memories_expiry` (`expires_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lw_relationships` (
  `character_guid` INT UNSIGNED NOT NULL,
  `target_guid` INT UNSIGNED NOT NULL,
  `affinity` SMALLINT NOT NULL DEFAULT 0,
  `trust` SMALLINT NOT NULL DEFAULT 0,
  `familiarity` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `rivalry` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `interaction_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `last_interaction_at` TIMESTAMP NULL DEFAULT NULL,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`character_guid`, `target_guid`),
  KEY `idx_lw_relationships_target` (`target_guid`),
  KEY `idx_lw_relationships_affinity` (`character_guid`, `affinity`),
  KEY `idx_lw_relationships_rivalry` (`character_guid`, `rivalry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
