  `primary_goal` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `activity_archetype` TINYINT UNSIGNED NOT NULL DEFAULT 3,
  `ambition` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `sociability` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `competitiveness` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `curiosity` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `loyalty` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `patience` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `risk_tolerance` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `tactical_intelligence` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `strategic_intelligence` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `social_intelligence` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `economic_intelligence` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `game_knowledge` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `adaptability` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `attention` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `target_weekly_hours` SMALLINT UNSIGNED NOT NULL DEFAULT 20,
  `minimum_session_minutes` SMALLINT UNSIGNED NOT NULL DEFAULT 45,
  `maximum_session_minutes` SMALLINT UNSIGNED NOT NULL DEFAULT 180,
  `schedule_consistency` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `skip_session_chance` TINYINT UNSIGNED NOT NULL DEFAULT 20,
  `marathon_session_chance` TINYINT UNSIGNED NOT NULL DEFAULT 5,
  `burnout_sensitivity` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `leveling_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `questing_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `dungeon_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `raid_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `pvp_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `profession_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `collecting_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `socializing_preference` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `last_seen_at` TIMESTAMP NULL DEFAULT NULL,
  PRIMARY KEY (`character_guid`),
